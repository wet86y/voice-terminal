// @vitest-environment jsdom
import { mount } from '@vue/test-utils'
import { reactive } from 'vue'
import { describe, expect, it } from 'vitest'
import InstructionEditorRow from './InstructionEditorRow.vue'

describe('自定义指令的可选关键词', () => {
  it('兼容缺少关键词的旧行，支持多词添加、去重与逐项删除', async () => {
    const row = reactive({ trigger: '要求静默', target: 'shadow', instruction: '提前静默', enabled: true, keywords: undefined as string[] | undefined })
    const wrapper = mount(InstructionEditorRow, { props: { row, expanded: true } })
    const input = wrapper.get('input[aria-label="触发关键词（选填）"]')
    await input.setValue('静默，退下、静默')
    await input.trigger('keydown', { key: 'Enter' })
    expect(row.keywords).toEqual(['静默', '退下'])
    await wrapper.get('button[aria-label="移除触发关键词 静默"]').trigger('click')
    expect(row.keywords).toEqual(['退下'])
    wrapper.unmount()
  })
  it('保存前失焦提交输入，非法词明确报错且禁用时不可编辑', async () => {
    const row = reactive({ trigger: '要求静默', target: 'voice', instruction: '等待', enabled: true, keywords: [] as string[] })
    const wrapper = mount(InstructionEditorRow, { props: { row, expanded: true } })
    const input = wrapper.get('input[aria-label="触发关键词（选填）"]')
    await input.setValue('静')
    await input.trigger('blur')
    expect(row.keywords).toEqual(['静'])
    expect(wrapper.get('[role="alert"]').text()).toContain('2～4 个汉字')
    await wrapper.setProps({ disabled: true })
    expect(wrapper.get<HTMLInputElement>('input[aria-label="触发关键词（选填）"]').element.disabled).toBe(true)
    wrapper.unmount()
  })
  it('中文输入法确认文字时不提前提交', async () => {
    const row = reactive({ trigger: '', target: 'voice', instruction: '', enabled: true, keywords: [] as string[] })
    const wrapper = mount(InstructionEditorRow, { props: { row, expanded: true } })
    const input = wrapper.get('input[aria-label="触发关键词（选填）"]')
    await input.setValue('静默')
    await input.trigger('keydown', { key: 'Enter', isComposing: true })
    expect(row.keywords).toEqual([])
    await input.trigger('keydown', { key: 'Enter' })
    expect(row.keywords).toEqual(['静默'])
    wrapper.unmount()
  })
  it('收起显示名称、展开按钮与右侧开关，展开后两行编辑并支持名称回退', async () => {
    const row = reactive({ id: 'quiet', name: '', trigger: '要求进入静默', target: 'shadow', instruction: '提前静默', enabled: true, keywords: ['静默'] })
    const wrapper = mount(InstructionEditorRow, { props: { row, removable: true } })
    expect(wrapper.get('.instruction-name').text()).toBe('要求进入静默')
    expect(wrapper.findAll('input')).toHaveLength(1)
    expect(wrapper.find('textarea').exists()).toBe(false)
    expect(wrapper.find('.instruction-entry-actions').exists()).toBe(false)
    expect(wrapper.get('.instruction-collapse').text()).toBe('展开')
    expect(wrapper.get('.instruction-collapse').attributes('aria-expanded')).toBe('false')
    await wrapper.get('.instruction-collapse').trigger('click')
    expect(wrapper.get('.instruction-collapse').text()).toBe('收起')
    expect(wrapper.get('.instruction-collapse').attributes('aria-expanded')).toBe('true')
    expect(wrapper.findAll('.instruction-main-fields > .form-field').map(field => field.get('span').text())).toEqual(['触发语义', '执行目标'])
    expect(wrapper.get('.instruction-secondary-fields').text()).toContain('执行位置')
    await wrapper.get('input[aria-label="指令名称（选填）"]').setValue('静默模式')
    await wrapper.get('.instruction-collapse').trigger('click')
    expect(wrapper.get('.instruction-name').text()).toBe('静默模式')
    row.name = ' '
    await wrapper.vm.$nextTick()
    expect(wrapper.get('.instruction-name').text()).toBe('要求进入静默')
    wrapper.unmount()
  })
  it('开关不展开条目，发出单独启停事件并等待保存确认', async () => {
    const row = reactive({ name: '静默', trigger: '进入静默', target: 'shadow', instruction: '提前静默', enabled: true })
    const wrapper = mount(InstructionEditorRow, { props: { row } })
    await wrapper.get('input[role="switch"]').setValue(false)
    expect(wrapper.emitted('toggle')).toEqual([[false]])
    expect(row.enabled).toBe(true)
    expect(wrapper.get<HTMLInputElement>('input[role="switch"]').element.checked).toBe(true)
    expect(wrapper.find('.instruction-editor').exists()).toBe(false)
    wrapper.unmount()
  })
})
