"""Build state（构建状态）：按内容验证输入与产物，不以时间戳或版本号代替复用依据。"""
from __future__ import annotations

import argparse
from concurrent.futures import ThreadPoolExecutor
import hashlib
import json
import os
from pathlib import Path
import stat
import subprocess
import sys
import time

ROOT = Path(__file__).resolve().parents[1]
IGNORED = {'.git', 'node_modules', '__pycache__', 'target', 'dist', 'gen', 'autogenerated', 'voice-terminal-build'}
FIELDS = {'schema': '构建状态格式', 'stage': '构建阶段', 'inputs': '输入路径与内容摘要',
          'outputs': '产物路径与内容摘要', 'fingerprint': '全部输入的内容身份'}


def digest(path: Path) -> str:
    with path.open('rb') as stream:
        return hashlib.file_digest(stream, 'sha256').hexdigest()


def inventory(root: Path, paths: list[str]) -> dict[str, str]:
    result = {}
    content = []
    parents_checked = set()
    last_notice = time.monotonic()
    def collect(path: Path, info=None):
        nonlocal last_notice
        name = path.relative_to(root).as_posix()
        try:
            info = info or path.lstat()
        except FileNotFoundError:
            result[name] = '<missing>'
            return
        if stat.S_ISLNK(info.st_mode) or getattr(info, 'st_file_attributes', 0) & 0x400:
            raise ValueError(f'构建输入或产物不能是目录联接或符号链接：{name}')
        if stat.S_ISREG(info.st_mode):
            content.append((name, path))
            result[name] = '<file>'
        elif stat.S_ISDIR(info.st_mode):
            result[name + '/'] = '<directory>'
            with os.scandir(path) as stream:
                children = sorted(stream, key=lambda child: child.name)
            for child in children:
                if child.name not in IGNORED:
                    collect(Path(child.path), child.stat(follow_symlinks=False))
        else:
            raise ValueError(f'构建输入含特殊文件：{name}')
        if time.monotonic() - last_notice >= 2:
            print(f'正在收集构建清单：已处理 {len(result)} 个路径。', flush=True)
            last_notice = time.monotonic()
    for relative in paths:
        path = root / relative
        for ancestor in path.parents:
            if ancestor == root:
                break
            if ancestor in parents_checked:
                break
            if ancestor.is_symlink() or ancestor.is_junction():
                raise ValueError(f'构建路径的父目录不能是链接：{relative}')
            parents_checked.add(ancestor)
        collect(path)
    # 小文件逐个打开会累积过滤器等待；有界并行摘要，不复用跨轮次的时间戳结论。
    with ThreadPoolExecutor(max_workers=16, thread_name_prefix='build-input-hash') as workers:
        for index, ((name, _), value) in enumerate(zip(content, workers.map(lambda item: digest(item[1]), content)), 1):
            result[name] = value
            if time.monotonic() - last_notice >= 2:
                print(f'正在核对构建内容：{index}/{len(content)} 个文件。', flush=True)
                last_notice = time.monotonic()
    return result


def paths_for(stage: str, optimization='release', components='desktop,bootstrap', qualification=False):
    native = ['apps/desktop/Cargo.toml', 'apps/desktop/Cargo.lock', 'apps/desktop/common',
              'apps/desktop/boot', 'integrations/downloader', 'config/update-kit.lock.json',
              '.local/build/update-kit/native',
              'scripts/build-desktop.ps1', 'scripts/download-sources.ps1', '.cargo/config.toml',
              '.local/tools/rust/cargo/config.toml']
    if stage == 'frontend':
        return (['apps/frontend', 'apps/desktop/boot', 'package.json', 'package-lock.json'],
                ['.local/build/frontend'])
    if stage == 'plugin':
        return (['integrations/dsh/voice-terminal', 'config/dsh', 'config/shadow_agent',
                 'scripts/build-dsh-client.mjs', 'scripts/project-root.mjs',
                 '.local/build/dsh/source/package.json', '.local/build/dsh/source/pnpm-lock.yaml',
                 '.local/build/dsh/source/tsconfig.json', '.local/build/dsh/source/tsconfig.base.json'],
                ['.local/build/dsh/bundles/voice-terminal'])
    if stage == 'product':
        outputs = []
        for component in components.split(','):
            if component == 'desktop':
                native += ['apps/desktop/src-tauri', '.local/build/frontend']
                outputs.append(f'.local/build/desktop/product/{optimization}/VoiceTerminalDesktop.exe')
            elif component == 'bootstrap':
                native += ['apps/desktop/bootstrap']
                outputs.append(f'.local/build/desktop/product/{optimization}/VoiceTerminal.exe')
            elif component == 'demo':
                native += ['apps/desktop/bootstrap']
                outputs.append(f'.local/build/desktop/product/{optimization}/VoiceTerminalUIDemo.exe')
            else:
                raise ValueError('未知原生入口职责')
        return native, outputs
    if stage == 'installer':
        cache = 'installer-qualification' if qualification else 'installer'
        return (native + ['apps/desktop/installer', '.local/build/program-package/program.zip'],
                [f'.local/build/desktop/{cache}/{optimization}/VoiceTerminalSetup.exe'])
    if stage == 'package':
        return (['voice_terminal', 'apps/server', 'apps/frontend', 'apps/desktop/common',
                 'apps/desktop/bootstrap', 'apps/desktop/src-tauri', 'apps/desktop/Cargo.toml',
                 'apps/desktop/Cargo.lock', 'integrations/dsh/voice-terminal',
                 '.local/build/update-kit/native',
                 'config', 'assets/smart-turn', 'scripts',
                 'package.json', 'pyproject.toml', 'docs/guides/模型运行环境配置指南.md',
                 'apps/desktop/boot', '.local/build/frontend', '.local/build/dsh/bundles/voice-terminal',
                 '.local/build/desktop/product/release/VoiceTerminal.exe',
                 '.local/build/desktop/product/release/VoiceTerminalDesktop.exe',
                 '.local/build/desktop/product/build-stamp.json', '.local/build/tools/desktop-crt',
                 '.local/build/tools/7zip', '.local/build/runtime-lock',
                 '.local/models/speaker/campplus-zh-cn-common'],
                ['.local/build/program-package/program.zip', '.local/build/program-package/package-info.json'])
    raise ValueError('未知构建阶段')


def tool_identity(root: Path, stage: str) -> dict:
    result = {'python': sys.version, 'state_script': digest(Path(__file__))}
    if stage in {'frontend', 'plugin'}:
        result['node'] = subprocess.check_output(['node', '--version'], text=True).strip()
    if stage in {'product', 'installer'}:
        cargo = root / '.local/tools/rust/cargo/bin/cargo.exe'
        result['compiler'] = subprocess.check_output([str(cargo.with_name('rustc.exe')), '--version', '--verbose'], text=True).strip()
        result['environment'] = {name: os.environ.get(name) for name in
                                 ('RUSTFLAGS', 'CARGO_ENCODED_RUSTFLAGS', 'TAURI_CONFIG', 'REMOVE_UNUSED_COMMANDS')}
        if stage == 'installer':
            package = Path(os.environ['VOICE_PROGRAM_PACKAGE'])
            if package.is_symlink() or package.is_junction():
                raise ValueError('安装器程序包不能是链接')
            result['embedded_package'] = digest(package)
    return result


def state_path(root: Path, stage: str, optimization: str, components: str, qualification: bool) -> Path:
    key = stage
    if stage in {'product', 'installer'}:
        key += f'-{optimization}-{components.replace(",", "-")}'
        if qualification:
            key += '-qualification'
    return root / '.local/build/desktop/stages' / (key + '.json')


def inputs_for(root, stage, optimization, components, qualification, build):
    sources, outputs = paths_for(stage, optimization, components, qualification)
    if stage in {'plugin', 'package'}:
        source = root / '.local/build/dsh/source'
        if (source / '.git').exists():
            # 仅盘点上游源码索引与未忽略的新源码，不扫描其已安装依赖和生成物。
            listed = subprocess.check_output(['git', '-C', str(source), 'ls-files', '-z', '--cached',
                                               '--others', '--exclude-standard', '--', 'packages', 'python/sdk-runtime'])
            sources += ['.local/build/dsh/source/' + name for name in listed.decode('utf-8').split('\0')
                        if name and not any(part in IGNORED for part in Path(name).parts)]
    inputs = inventory(root, sources)
    inputs['<tools>'] = json.dumps(tool_identity(root, stage), sort_keys=True)
    inputs['<options>'] = json.dumps([optimization, components, qualification])
    fingerprint = hashlib.sha256(json.dumps(inputs, sort_keys=True).encode()).hexdigest()
    return inputs, fingerprint, outputs


def write_state(path: Path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    pending = path.with_suffix('.writing.json')
    pending.write_text(json.dumps(value, ensure_ascii=False, sort_keys=True, indent=2) + '\n', encoding='utf-8')
    pending.replace(path)


def verify_package(root: Path):
    directory = root / '.local/build/program-package'
    info = json.loads((directory / 'package-info.json').read_text('utf-8-sig'))
    archive = directory / 'program.zip'
    if archive.stat().st_size != info['size'] or digest(archive) != info['sha256']:
        raise ValueError('已有程序包大小或摘要不符，拒绝安装或构建安装器')
    return info


def run(root, operation, stage, optimization='release', components='desktop,bootstrap', qualification=False, build=''):
    path = state_path(root, stage, optimization, components, qualification)
    pending = path.with_suffix('.pending.json')
    if operation == 'check' and not path.is_file():
        print('需要更新：缺少本阶段构建记录')
        return False
    inputs, fingerprint, outputs = inputs_for(root, stage, optimization, components, qualification, build)
    base = {'schema': 1, 'stage': stage, 'inputs': inputs, 'fingerprint': fingerprint, 'fields': FIELDS}
    if operation == 'begin':
        write_state(pending, base)
        return True
    if operation == 'record':
        before = json.loads(pending.read_text('utf-8'))
        if before['fingerprint'] != fingerprint:
            raise ValueError('构建期间输入发生变化，产物未登记为可复用；请完成编辑后重新执行')
        produced = inventory(root, outputs)
        if not produced or '<missing>' in produced.values():
            raise ValueError('构建未生成全部预期产物')
        base['outputs'] = produced
        write_state(path, base)
        pending.unlink()
        return True
    try:
        recorded = json.loads(path.read_text('utf-8'))
        if recorded['schema'] != 1 or recorded['fingerprint'] != fingerprint:
            changed = [name for name in sorted(set(inputs) | set(recorded['inputs']))
                       if inputs.get(name) != recorded['inputs'].get(name)]
            print('需要更新：输入内容变化，' + '、'.join(changed[:5]))
            return False
        if recorded['outputs'] != inventory(root, outputs):
            print('需要更新：构建产物缺失或内容变化')
            return False
        if stage == 'package':
            info = verify_package(root)
            if build and info['build'] != build:
                print('需要更新：指定构建编号与已有包不同')
                return False
    except (OSError, ValueError, KeyError, TypeError):
        print('需要更新：缺少有效的输入与产物记录')
        return False
    print('复用已核验阶段：' + stage)
    return True


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('operation', choices=['check', 'begin', 'record'], help='operation（核对、开始或登记）')
    parser.add_argument('--stage', required=True, choices=['frontend', 'plugin', 'product', 'installer', 'package'], help='stage（构建阶段）')
    parser.add_argument('--optimization', default='release', choices=['debug', 'release'], help='optimization（优化模式）')
    parser.add_argument('--components', default='desktop,bootstrap', help='components（原生入口职责）')
    parser.add_argument('--qualification', action='store_true', help='qualification（隔离验收模式）')
    parser.add_argument('--build', default='', help='build（指定程序包编号）')
    args = parser.parse_args()
    try:
        ok = run(ROOT, **vars(args))
    except (OSError, ValueError, KeyError) as error:
        print(str(error), file=sys.stderr)
        sys.exit(1)
    sys.exit(0 if ok else 3)
